"""Maintain ndk-build's source inventory from the current component layout."""
import argparse
from pathlib import Path
from source_layout import REPO, ROOT, encoder_sources, ar_sources, ar_shared_sources
from math_layout import math_sources

DEST = ROOT / 'platform/android/sources.mk'


def render():
    groups = {'MATH': math_sources(),
              'COMMON': [ROOT / p for p in ['common/src/buffer/cirbuf.c',
                  'common/src/dsp/adsq_tables.c', 'common/src/memory/workspace.c',
                  'platform/common/memory.c']],
              'DSP': sorted((ROOT / 'common/src/dsp').glob('*.c'))}
    groups['DSP'] = [p for p in groups['DSP'] if p.name != 'adsq_tables.c']
    shared = ar_shared_sources()
    groups['AR_SHARED'] = [p for p in shared if '/pcm/' not in p.as_posix()]
    groups['PCM'] = [p for p in shared if '/pcm/' in p.as_posix()]
    for version in ['v4', 'v5']:
        sources = encoder_sources(version)
        groups['ENCODER_' + version.upper()] = [p for p in sources if not p.name.endswith('BT_enc.c')]
        groups['BT_' + version.upper()] = [p for p in sources if p.name.endswith('BT_enc.c')]
        groups['AR_' + version.upper()] = ar_sources(version)
        groups['DECODER_' + version.upper()] = sorted(
            p for d in [ROOT / 'decoder/src' / version, ROOT / 'decoder/src/api' / version]
            for p in d.rglob('*.c'))
    text = '# Generated by tools/generate_android_sources.py; paths relative to project root.\n'
    for name, sources in groups.items():
        assert sources and len(set(sources)) == len(sources), name
        assert all(p.is_file() for p in sources), name
        text += '\nLHDC_SOURCES_' + name + ' := \\\n' + ' \\\n'.join(
            '  ' + p.relative_to(REPO).as_posix() for p in sources) + '\n'
    return text


def generate(check=False):
    text = render()
    if check:
        if not DEST.is_file() or DEST.read_text(encoding='utf8') != text:
            raise SystemExit('Stale Android inventory; run tools/generate_android_sources.py')
    else:
        DEST.write_text(text, encoding='utf8', newline='\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    generate(parser.parse_args().check)
