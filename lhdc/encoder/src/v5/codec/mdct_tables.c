/* Copy production rotations, sampling the post master table at power-of-two strides and scaling exactly by powers of two.
 * Only bitwise-verified lengths and 16/24-bit scaling are handled; other configurations use dynamic formulas without writes here.
 * Master/results are normal or zero; scaling neither overflows/underflows nor adds rounding. */
int lhdc_v5_mdct_copy_rotations(int frame_samples, int shift_bits,
                                kiss_fft_cpx *pre, kiss_fft_cpx *post) {
    if (!pre || !post || (shift_bits != 7 && shift_bits != 15))
        return 0;
    const kiss_fft_cpx *source;
    switch (frame_samples) {
    case 120:
        source = pre_rotation_120;
        break;
    case 240:
        source = pre_rotation_240;
        break;
    case 480:
        source = pre_rotation_480;
        break;
    case 960:
        source = pre_rotation_960;
        break;
    case 1920:
        source = pre_rotation_1920;
        break;
    default:
        return 0;
    }
    const int length = frame_samples / 2;
    const int stride = 1920 / frame_samples;
    const float scale = (float)(stride * (shift_bits == 15 ? 256 : 1));
    memcpy(pre, source, (size_t)length * sizeof *pre);
    for (int k = 0; k < length; ++k) {
        post[k].r = post_rotation_1920[k * stride].r * scale;
        post[k].i = post_rotation_1920[k * stride].i * scale;
    }
    return 1;
}

