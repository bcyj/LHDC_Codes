/* Copy fixed encoding FFT coefficients at power-of-two strides; misses/null output do not write. */
int lhdc_v5_mdct_copy_fixed_twiddles(int length, LhdcFftFixed32Complex *twiddles) {
#if LHDC_PLATFORM_FIXED_DSP_TABLES
    if (!twiddles)
        return 0;
    unsigned stride;
    switch (length) {
    case 60:
        stride = 8;
        break;
    case 120:
        stride = 4;
        break;
    case 240:
        stride = 2;
        break;
    case 480:
        stride = 1;
        break;
    default:
        return 0;
    }
    for (int i = 0; i < length; ++i)
        twiddles[i] = fixed_fft_forward_480[(unsigned)i * stride];
    return 1;
#else
    (void)length;
    (void)twiddles;
    return 0;
#endif
}
