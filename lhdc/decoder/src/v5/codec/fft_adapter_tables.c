/* Copy verified fixed-length coefficients; unsupported lengths or null output return zero without writes.
 * Four lengths sample the same master table exactly; inverse imaginary parts negate, with no INT32_MIN entries. */
int lhdc_v5_fft_copy_twiddles(int length, int inverse, LhdcFftFixed32Complex *twiddles) {
    if (!twiddles)
        return 0;
    unsigned stride;
    switch (length) {
    case 60:
        stride = 8;
        break;
    case 120:
        stride = 4;
        break;
    case 240:
        stride = 2;
        break;
    case 480:
        stride = 1;
        break;
    default:
        return 0;
    }
    for (int i = 0; i < length; ++i) {
        const LhdcFftFixed32Complex value = forward_480[(unsigned)i * stride];
        twiddles[i].r = value.r;
        twiddles[i].i = inverse ? -value.i : value.i;
    }
    return 1;
}
