/* Copy fixed-size pre/post coefficients; return zero without writes for other sizes. */
int lhdc_v5_time_copy_rotations(int size, LhdcFftFixed32Complex *pre, LhdcFftFixed32Complex *post) {
    if (!pre || !post)
        return 0;
    const LhdcFftFixed32Complex *source;
    unsigned stride;
    switch (size) {
    case 480:
        source = pre_480;
        stride = 4;
        break;
    case 960:
        source = pre_960;
        stride = 2;
        break;
    case 1920:
        source = pre_1920;
        stride = 1;
        break;
    default:
        return 0;
    }
    const int length = size / 4;
    memcpy(pre, source, (size_t)length * sizeof *pre);
    for (int i = 0; i < length; ++i)
        post[i] = post_1920[(unsigned)i * stride];
    return 1;
}

